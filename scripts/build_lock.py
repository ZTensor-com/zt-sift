#!/usr/bin/env python3
"""Write requirements.lock for the Lambda image by resolving requirements.txt against the project's wheel cache.

Resolves for Linux amd64 / Python 3.12 in a container with no package index, so every package must already be in
wheels/. Needs Docker. Regenerating after new wheels were added can move package versions, so treat the committed lock files as the record of what was deployed. To refresh the cache, download the wheels for Linux amd64 / Python 3.12:
    pip download --only-binary=:all: --platform manylinux2014_x86_64 --python-version 3.12 -r requirements.txt -d wheels
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def main():
    source = ROOT / "requirements.txt"
    target = ROOT / "requirements.lock"
    with tempfile.TemporaryDirectory() as work:
        work = Path(work)
        (work / "requirements.txt").write_text(source.read_text())
        result = subprocess.run([
            "docker", "run", "--rm", "--platform", "linux/amd64", "-v", f"{ROOT / 'wheels'}:/cache:ro", "-v", f"{work}:/work",
            "python:3.12-slim", "pip", "install", "--dry-run", "--ignore-installed", "--quiet", "--report", "/work/report.json",
            "--no-index", "--find-links", "/cache", "-r", "/work/requirements.txt"],
            capture_output=True, text=True)
        if result.returncode:
            sys.exit("could not resolve from the local wheel cache:\n" + (result.stderr or result.stdout)[-1500:])
        report = json.loads((work / "report.json").read_text())
    names = sorted((e["metadata"]["name"], e["metadata"]["version"]) for e in report["install"])
    lines = ["# Generated by scripts/build_lock.py for linux/amd64, Python 3.12. Do not edit."]
    lines += [f"{name}=={version}" for name, version in names]
    target.write_text("\n".join(lines) + "\n")
    print(f"{len(names)} packages pinned, all from wheels/")


if __name__ == "__main__":
    sys.exit(main())
